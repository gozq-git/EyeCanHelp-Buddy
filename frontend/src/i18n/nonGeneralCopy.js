export function getCopy(language = 'en') {
  const selected = COPY[language] || COPY.en
  return (key) => selected[key] || COPY.en[key] || ''
}

export function formatCopy(template, params = {}) {
  return Object.entries(params).reduce((value, [key, replacement]) => {
    return value.replaceAll(`{${key}}`, String(replacement ?? ''))
  }, String(template || ''))
}
